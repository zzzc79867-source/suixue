export function teachContext(subject, unit, card) {
  const context = UNIT_SCENES.get(subject.id + ':' + unit.title) || {
    scene: '先不要急着记结论，先想这个知识点要解决什么问题。',
    ask: '如果只看标题，你猜它的核心对象和条件是什么？',
    explain: '先用一句话抓住主线，再展开课本要点。'
  };

  const titleQuestion = /方程|公式/.test(card.title) ? '这个公式的适用对象和条件分别是什么？'
    : /定律|定则/.test(card.title) ? '它约束的是哪一类过程？'
    : /方法/.test(card.title) ? '什么时候用它？步骤是什么？'
    : /判据/.test(card.title) ? '它判断什么方向或状态？'
    : /连接|三相/.test(card.title) ? '连接方式如何改变电压、电流和功率？'
    : /二极管|三极管|运放/.test(card.title) ? '器件工作区决定了什么？'
    : /触发器|计数器/.test(card.title) ? '它怎么保存或推进状态？'
    : context.ask;

  return {
    ...context,
    ask: titleQuestion,
    why: '“' + card.title + '”是' + unit.title.replace(/^第\d+章\s*/, '') + '里的关键模型；考试常考它的适用条件、对象和符号方向。'
  };
}
